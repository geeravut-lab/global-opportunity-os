export function stateLabel(lang: "th" | "en", state: string) {
  const t = s2Text[lang];
  return state in t ? t[state as keyof typeof t] : state;
}
export function ruleLabel(
  lang: "th" | "en",
  r: { field: string; op: string; value?: unknown; expected?: unknown },
) {
  const fields = {
    th: {
      country: "ประเทศ",
      region: "พื้นที่",
      language: "ภาษา",
      adult: "ผู้ใหญ่",
      remote: "สะดวกออนไลน์",
      hours: "ชั่วโมงต่อสัปดาห์",
    },
    en: {
      country: "Country",
      region: "Area",
      language: "Language",
      adult: "Adult",
      remote: "Online participation",
      hours: "Hours per week",
    },
  };
  const ops = {
    th: { eq: "ตรงกับ", in: "หนึ่งใน", gte: "อย่างน้อย", lte: "ไม่เกิน" },
    en: { eq: "equals", in: "one of", gte: "at least", lte: "at most" },
  };
  const v = r.value ?? r.expected;
  const value =
    typeof v === "boolean"
      ? v
        ? s2Text[lang].yes
        : s2Text[lang].no
      : Array.isArray(v)
        ? v.join(", ")
        : String(v);
  return `${fields[lang][r.field as keyof typeof fields.th] ?? r.field} ${ops[lang][r.op as keyof typeof ops.th] ?? r.op} ${value}`;
}
