export function authErrorText(code: string, lang: "th" | "en"): string {
  const t = authText[lang];
  if (code === "CREDENTIALS_REJECTED") return t.credentials;
  if (code === "MFA_CODE_REJECTED") return t.mfaInvalid;
  if (code === "MFA_REQUIRED") return t.mfaRequired;
  if (code === "STATE_CONFLICT") return t.conflict;
  if (code === "NOT_FOUND") return t.denied;
  if (code === "SIGN_IN_REQUIRED" || code === "SESSION_UNAVAILABLE")
    return t.sessionExpired;
  if (code === "TRY_LATER") return t.tryLater;
  if (
    code === "AUTH_NOT_CONFIGURED" ||
    code === "GOOGLE_NOT_CONFIGURED" ||
    code === "DATABASE_NOT_READY"
  )
    return t.unavailable;
  return t.error;
}
